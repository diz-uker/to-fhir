"""Tests for python_constants_generator — verifies generated source structure."""

from __future__ import annotations

from ig_codegen.ig_package_model import (
    ConceptConstant,
    ExtensionValueType,
    IgPackageModel,
    NamingSystemEntry,
)
from ig_codegen.python_constants_generator import generate


def _make_model(**overrides) -> IgPackageModel:
    return IgPackageModel(
        package_name=overrides.get("package_name", "de.example.test"),
        package_version=overrides.get("package_version", "1.0.0"),
        code_systems=overrides.get("code_systems", {}),
        profiles=overrides.get("profiles", {}),
        extensions=overrides.get("extensions", {}),
        code_system_concepts=overrides.get("code_system_concepts", {}),
        extension_value_types=overrides.get("extension_value_types", {}),
        naming_systems=overrides.get("naming_systems", {}),
    )


class TestGenerateHeader:
    def test_generated_comment(self) -> None:
        model = _make_model()
        source = generate(model, "Test")
        assert "# Generated by ig-codegen from de.example.test 1.0.0." in source

    def test_future_annotations(self) -> None:
        source = generate(_make_model(), "Test")
        assert "from __future__ import annotations" in source

    def test_no_enum_import_when_no_concepts(self) -> None:
        source = generate(_make_model(), "Test")
        assert "import enum" not in source

    def test_no_protocol_import_when_no_extensions(self) -> None:
        source = generate(_make_model(), "Test")
        assert "from typing import Protocol" not in source

    def test_enum_import_when_concepts_present(self) -> None:
        model = _make_model(
            code_systems={"MII_CS_TEST": "https://example.com/cs"},
            code_system_concepts={
                "MII_CS_TEST": [ConceptConstant("KURATIV", "kurativ", "Kurativ")]
            },
        )
        source = generate(model, "Test")
        assert "import enum" in source

    def test_protocol_import_when_extensions_present(self) -> None:
        model = _make_model(
            extensions={"MII_EX_TEST": "https://example.com/ext"},
        )
        source = generate(model, "Test")
        assert "from typing import Protocol" in source
        assert "class _HasExtensions(Protocol)" in source


class TestCodeSystemsClass:
    def test_url_constant(self) -> None:
        model = _make_model(
            code_systems={"MII_CS_TEST": "https://example.com/cs"},
        )
        source = generate(model, "Test")
        assert "class CodeSystems" in source
        assert 'MII_CS_TEST = "https://example.com/cs"' in source

    def test_enum_class_generated(self) -> None:
        model = _make_model(
            code_systems={"MII_CS_TEST": "https://example.com/cs"},
            code_system_concepts={
                "MII_CS_TEST": [
                    ConceptConstant("KURATIV", "kurativ", "Kurativ"),
                    ConceptConstant("PALLIATIV", "palliativ", None),
                ]
            },
        )
        source = generate(model, "Test")
        assert "class MiiCsTest(enum.Enum)" in source
        assert 'KURATIV = ("kurativ", "Kurativ")' in source
        assert 'PALLIATIV = ("palliativ", None)' in source

    def test_enum_has_coding_import(self) -> None:
        model = _make_model(
            code_systems={"MII_CS_TEST": "https://example.com/cs"},
            code_system_concepts={
                "MII_CS_TEST": [ConceptConstant("KURATIV", "kurativ", "Kurativ")]
            },
        )
        source = generate(model, "Test")
        assert "from fhir.resources.coding import Coding" in source

    def test_enum_methods_present(self) -> None:
        model = _make_model(
            code_systems={"MII_CS_TEST": "https://example.com/cs"},
            code_system_concepts={
                "MII_CS_TEST": [ConceptConstant("KURATIV", "kurativ", "Kurativ")]
            },
        )
        source = generate(model, "Test")
        assert "def url(self) -> str" in source
        assert "def coding(self) -> Coding" in source
        assert "def from_value(cls, code: str)" in source
        assert "def from_value_or_raise(cls, code: str)" in source


