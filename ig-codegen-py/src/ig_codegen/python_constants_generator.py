"""Renders an IgPackageModel as a Python source file.

One module per FHIR IG package with nested CodeSystems, Profiles, Extensions, and
NamingSystems inner classes.

CodeSystems get URL constants (UPPER_SNAKE_CASE class attributes) and, when the
content is complete, an enum.Enum subclass with url(), coding(), from_value(), and
from_value_or_raise() helpers.

Extensions get a URL constant, a factory @staticmethod, and a getter @staticmethod
taking a _HasExtensions Protocol instance.

NamingSystems get a nested class per NamingSystem with type-keyed string attributes.
"""

from __future__ import annotations

from pathlib import Path

from .code_writer import CodeWriter
from .ig_package_model import ExtensionValueType, IgPackageModel
from .name_utils import to_pascal_case, to_snake_case

# FHIR primitive/complex type codes → (Python type name, Extension.value[x] field)
